/// @p count pixels of @p pixel.
inline std::vector<std::uint8_t> repeat(const std::vector<std::uint8_t>& pixel, int count)
{
    std::vector<std::uint8_t> out;
    for (int i = 0; i < count; ++i) out.insert(out.end(), pixel.begin(), pixel.end());
    return out;
}

