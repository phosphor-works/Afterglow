// The pixel at x, y of TiffLzw and the other TIFF files of a pattern, as
// 0xRRGGBB: values that LZW compresses little.
inline std::uint32_t TiffPattern(int x, int y)
{
    const std::uint32_t r = std::uint32_t(x * x * 7 + y * 13) & 255;
    const std::uint32_t g = std::uint32_t((x * 31) ^ (y * 17)) & 255;
    const std::uint32_t b = std::uint32_t(x * y * 5 + 3) & 255;
    return r << 16 | g << 8 | b;
}

